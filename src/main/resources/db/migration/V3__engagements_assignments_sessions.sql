CREATE TABLE support_session (
    id BIGINT NOT NULL AUTO_INCREMENT,
    display_code VARCHAR(16) NOT NULL,
    engagement_id BIGINT NOT NULL,
    assignment_id BIGINT NOT NULL,
    series_id BIGINT NULL,
    occurrence_key VARCHAR(80) NULL,
    candidate_id BIGINT NOT NULL,
    expert_id BIGINT NOT NULL,
    candidate_name_snapshot VARCHAR(160) NOT NULL,
    expert_name_snapshot VARCHAR(160) NOT NULL,
    scheduled_start DATETIME(6) NOT NULL,
    scheduled_end DATETIME(6) NOT NULL,
    source_timezone VARCHAR(64) NOT NULL,
    meeting_platform VARCHAR(16) NULL,
    meeting_url VARCHAR(500) NULL,
    topic VARCHAR(160) NULL,
    status VARCHAR(16) NOT NULL,
    cancellation_reason VARCHAR(500) NULL,
    candidate_attended TINYINT(1) NULL,
    expert_attended TINYINT(1) NULL,
    shared_summary TEXT NULL,
    created_by BIGINT NULL,
    created_on DATETIME(6) NOT NULL,
    modified_by BIGINT NULL,
    modified_on DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_session_display_code (display_code),
    UNIQUE KEY uk_session_occurrence (series_id, occurrence_key),
    KEY ix_session_engagement_status (engagement_id, status),
    KEY ix_session_candidate_time (candidate_id, scheduled_start),
    KEY ix_session_expert_time (expert_id, scheduled_start),
    CONSTRAINT chk_session_status CHECK (status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT fk_session_engagement FOREIGN KEY (engagement_id) REFERENCES support_engagement (id),
    CONSTRAINT fk_session_assignment FOREIGN KEY (assignment_id) REFERENCES expert_assignment (id),
    CONSTRAINT fk_session_series FOREIGN KEY (series_id) REFERENCES session_series (id),
    CONSTRAINT fk_session_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profile (id),
    CONSTRAINT fk_session_expert FOREIGN KEY (expert_id) REFERENCES expert_profile (id),
    CONSTRAINT fk_session_created_by FOREIGN KEY (created_by) REFERENCES user_account (id),
    CONSTRAINT fk_session_modified_by FOREIGN KEY (modified_by) REFERENCES user_account (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

