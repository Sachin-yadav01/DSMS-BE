CREATE TABLE support_engagement (
    id BIGINT NOT NULL AUTO_INCREMENT,
    display_code VARCHAR(16) NOT NULL,
    candidate_id BIGINT NOT NULL,
    title VARCHAR(160) NOT NULL,
    coordinator_user_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NULL,
    status VARCHAR(16) NOT NULL,
    schedule_timezone VARCHAR(64) NOT NULL,
    meeting_platform VARCHAR(16) NULL,
    default_meeting_url VARCHAR(500) NULL,
    shared_instructions TEXT NULL,
    current_terms_id BIGINT NULL,
    created_by BIGINT NULL,
    created_on DATETIME(6) NOT NULL,
    modified_by BIGINT NULL,
    modified_on DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_engagement_display_code (display_code),
    KEY ix_engagement_candidate (candidate_id),
    KEY ix_engagement_coordinator_status (coordinator_user_id, status),
    CONSTRAINT chk_engagement_status CHECK (status IN ('DRAFT', 'ACTIVE', 'PAUSED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_engagement_platform CHECK (meeting_platform IS NULL OR meeting_platform IN ('GOOGLE_MEET', 'ZOOM', 'OTHER')),
    CONSTRAINT fk_engagement_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profile (id),
    CONSTRAINT fk_engagement_coordinator FOREIGN KEY (coordinator_user_id) REFERENCES user_account (id),
    CONSTRAINT fk_engagement_created_by FOREIGN KEY (created_by) REFERENCES user_account (id),
    CONSTRAINT fk_engagement_modified_by FOREIGN KEY (modified_by) REFERENCES user_account (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE engagement_skill (
    engagement_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    PRIMARY KEY (engagement_id, skill_id),
    CONSTRAINT fk_engagement_skill_engagement FOREIGN KEY (engagement_id) REFERENCES support_engagement (id),
    CONSTRAINT fk_engagement_skill_skill FOREIGN KEY (skill_id) REFERENCES skill (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE engagement_terms (
    id BIGINT NOT NULL AUTO_INCREMENT,
    engagement_id BIGINT NOT NULL,
    plan_type VARCHAR(16) NOT NULL,
    currency CHAR(3) NOT NULL,
    hourly_rate DECIMAL(12, 2) NULL,
    monthly_base_fee DECIMAL(12, 2) NULL,
    included_seconds INT NULL,
    overage_enabled TINYINT(1) NOT NULL DEFAULT 0,
    overage_hourly_rate DECIMAL(12, 2) NULL,
    evidence_note VARCHAR(500) NULL,
    status VARCHAR(16) NOT NULL,
    effective_from DATE NOT NULL,
    created_by BIGINT NULL,
    created_on DATETIME(6) NOT NULL,
    modified_by BIGINT NULL,
    modified_on DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY ix_terms_engagement (engagement_id, effective_from),
    CONSTRAINT chk_terms_plan CHECK (plan_type IN ('HOURLY', 'MONTHLY')),
    CONSTRAINT chk_terms_status CHECK (status IN ('DRAFT', 'APPROVED')),
    CONSTRAINT fk_terms_engagement FOREIGN KEY (engagement_id) REFERENCES support_engagement (id),
    CONSTRAINT fk_terms_created_by FOREIGN KEY (created_by) REFERENCES user_account (id),
    CONSTRAINT fk_terms_modified_by FOREIGN KEY (modified_by) REFERENCES user_account (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

